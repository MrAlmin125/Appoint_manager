  var MONTHS = {
    en: ['January','February','March','April','May','June','July','August','September','October','November','December'],
    bn: ['জানুয়ারি','ফেব্রুয়ারি','মার্চ','এপ্রিল','মে','জুন','জুলাই','আগস্ট','সেপ্টেম্বর','অক্টোবর','নভেম্বর','ডিসেম্বর']
  };
  var WEEKDAYS_LONG = {
    en: ['Sunday','Monday','Tuesday','Wednesday','Thursday','Friday','Saturday'],
    bn: ['রবিবার','সোমবার','মঙ্গলবার','বুধবার','বৃহস্পতিবার','শুক্রবার','শনিবার']
  };
  var BN_DIGITS = ['০','১','২','৩','৪','৫','৬','৭','৮','৯'];

  function toBnDigits(str){
    return String(str).replace(/[0-9]/g, function(d){ return BN_DIGITS[+d]; });
  }

  function getLang(){
    var stored = localStorage.getItem('appt_lang');
    return (stored === 'en' || stored === 'bn') ? stored : 'bn';
  }
  function setLang(lang){
    localStorage.setItem('appt_lang', lang);
  }
  function t(key){
    var lang = getLang();
    return (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
  }
  function monthName(lang, idx){ return MONTHS[lang][idx]; }
  function weekdayLong(lang, idx){ return WEEKDAYS_LONG[lang][idx]; }
  function digits(lang, n){ return lang === 'bn' ? toBnDigits(n) : String(n); }

  function loadingHtml(){
    return '<span class="loading-spin">' + t('loading') + '</span>';
  }

  function formatShortDate(dstr){
    if (!dstr) return '';
    var p = dstr.split('-'); var y=parseInt(p[0],10), m=parseInt(p[1],10)-1, d=parseInt(p[2],10);
    var lang = getLang();
    var mon = MONTHS[lang][m];
    if (lang === 'en') mon = mon.slice(0,3);
    var dd = digits(lang, d < 10 ? '0'+d : d);
    return dd + ' ' + mon + ' ' + digits(lang, y);
  }

  function apply(){
    document.querySelectorAll('[data-i18n]').forEach(function(el){
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function(el){
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    document.documentElement.lang = getLang();
  }

  return { t: t, getLang: getLang, setLang: setLang, apply: apply, monthName: monthName, weekdayLong: weekdayLong, digits: digits, formatShortDate: formatShortDate, loadingHtml: loadingHtml };
